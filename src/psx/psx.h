/* The port's replacement for the PlayStation: RAM image, SDK functions and
 * the hardware behind them.
 *
 * The game's calls into the Psy-Q SDK are renamed psx_<Name> at build time
 * (tools/build_game.py), so the functions here never collide with the host
 * C library. Structures the game passes in are mirrored below with the
 * layout the SDK defines. */
#ifndef PSX_H
#define PSX_H

#include "../core/disc.h"
#include "../game/prelude.h"

#include <stdbool.h>
#include <stddef.h>
#include <stdint.h>

/* --- memory ------------------------------------------------------------- */

#define PSX_RAM_BASE 0x80000000u

/* Address inside the image for a PlayStation RAM address (KSEG0 or KUSEG). */
static inline void *psx_ptr(uint32_t psx_addr)
{
    return psx_ram + (psx_addr & (PSX_RAM_SIZE - 1));
}

static inline bool psx_in_ram(const void *p)
{
    return (const uint8_t *)p >= psx_ram && (const uint8_t *)p < psx_ram + PSX_RAM_SIZE;
}

/* --- modules ------------------------------------------------------------ */

typedef struct {
    uint32_t psx_addr;
    void (*native)(void); /* NULL if the port has no such function */
} PsxFunction;

typedef struct {
    uint32_t start, end; /* PlayStation addresses, end exclusive */
} PsxSpan;

/* The main executable or an overlay: where its file loads, the four bytes
 * an overlay file starts with, and what the build knows about its contents
 * (all sorted by address): its functions; the "slots", words the game's
 * declarations type as pointers; the "typed" spans those declarations
 * cover; and the spans holding the original code. */
typedef struct {
    const char *name;
    uint32_t load_addr;
    const unsigned char *overlay_id;
    const PsxFunction *functions;
    int function_count;
    const uint32_t *slots;
    int slot_count;
    const PsxSpan *typed;
    int typed_count;
    const PsxSpan *code;
    int code_count;
} PsxModule;

/* Generated by tools/build_game.py; the main executable comes first by name. */
extern const PsxModule psx_modules[];
extern const int psx_module_count;

/* The data the game loads from disc stores PlayStation addresses. Rewrites
 * those in [start, start + size), which must lie in the RAM image: function
 * addresses become the module's native functions and RAM addresses become
 * image addresses. Safe to repeat. */
void psx_relocate(const PsxModule *module, uint8_t *start, uint32_t size);
const PsxModule *psx_find_module(const char *name);

/* --- diagnostics -------------------------------------------------------- */

void psx_fatal(const char *fmt, ...) __attribute__((noreturn, format(printf, 1, 2)));
void psx_log(const char *fmt, ...) __attribute__((format(printf, 1, 2)));
/* Called by generated stubs for SDK functions the port does not have yet. */
int psx_unimplemented(const char *name);

/* A note of what the game side is doing, for the watchdog: set at the main
 * waiting and working points. */
extern const char *volatile psx_stage;
/* Called now and then from another thread: reports in the log if the game
 * has stopped finishing frames, with the last stage it was seen in. */
void psx_watchdog(void);

/* --- time and interrupts ------------------------------------------------ */

/* Runs pending "interrupt" work (disc events and the like). Called from SDK
 * functions the game uses while it waits. Does nothing inside a callback. */
void psx_poll(void);
/* Frames since the game started. */
int psx_frame_count(void);
/* True while a game callback is running in interrupt context. */
extern bool psx_in_interrupt;

/* Marks matching kernel events as occurred (see OpenEvent). */
void psx_deliver_event(uint32_t desc, int32_t spec);

/* Microseconds the game has spent drawing, for the port's speed report.
 * The reader resets it. */
extern uint32_t psx_draw_time_us;

/* --- sound ------------------------------------------------------------- */

#define SAMPLE_RATE 44100

/* Produces the next `frames` stereo samples and hands them to the platform. */
void psx_spu_mix(int frames);

/* Delivers a finished memory card operation to the game when it is due. */
void psx_card_poll(void);

/* --- disc --------------------------------------------------------------- */

void psx_cd_attach(Disc *disc);
/* Delivers at most one pending disc event to the game's callbacks. */
void psx_cd_poll(void);
/* Once per frame: paces sectors of real-time (video and audio) streams. */
void psx_cd_frame(void);

/* --- graphics ----------------------------------------------------------- */

#define VRAM_W 1024
#define VRAM_H 512

typedef struct {
    int16_t x, y, w, h;
} PsxRect;

extern uint16_t psx_vram[VRAM_W * VRAM_H];

void psx_gpu_reset(void);
/* Runs `count` words of GP0 commands (drawing primitives and settings). */
void psx_gpu_gp0(const uint32_t *words, int count);
void psx_gpu_fill(int x, int y, int w, int h, uint16_t color);
/* Delivers the drawing-complete callback if one is owed. */
void psx_gpu_poll(void);
/* True if the picture may have changed since the last call. */
bool psx_gpu_take_display_changed(void);
/* The display area the game selected, for presentation. */
void psx_gpu_get_display(PsxRect *area, bool *enabled, bool *rgb24);

/* Provided by the port (src/port/textures.c): called after the game has
 * copied an image into video memory, so the port can replace parts of it. */
void port_image_uploaded(const PsxRect *rect, const uint16_t *pixels);

/* --- input -------------------------------------------------------------- */

/* PlayStation pad buttons, as the bit set a digital pad reports (1 = down). */
enum {
    PSX_PAD_SELECT = 0x0001,
    PSX_PAD_START = 0x0008,
    PSX_PAD_UP = 0x0010,
    PSX_PAD_RIGHT = 0x0020,
    PSX_PAD_DOWN = 0x0040,
    PSX_PAD_LEFT = 0x0080,
    PSX_PAD_L2 = 0x0100,
    PSX_PAD_R2 = 0x0200,
    PSX_PAD_L1 = 0x0400,
    PSX_PAD_R1 = 0x0800,
    PSX_PAD_TRIANGLE = 0x1000,
    PSX_PAD_CIRCLE = 0x2000,
    PSX_PAD_CROSS = 0x4000,
    PSX_PAD_SQUARE = 0x8000
};

/* Writes the current buttons into the buffers the game registered. */
void psx_pad_update(uint16_t buttons);

/* --- frame -------------------------------------------------------------- */

/* Provided by the port's frontend (src/port/frame.c): shows the picture,
 * services the lower screen, and returns the pad state for the next frame.
 * Does not return if the player quits. */
uint16_t port_frame(void);

#endif
