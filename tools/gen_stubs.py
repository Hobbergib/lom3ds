#!/usr/bin/env python3
"""Writes placeholder definitions for SDK functions the port lacks.

Usage: gen_stubs.py NM OUT.c --want GAME_OBJ... --have PORT_OBJ...

Every psx_* symbol the game objects need and the port objects do not define
becomes a function that reports itself once and returns 0, so the program
links and the gap is visible at run time instead.
"""
import subprocess
import sys


def symbols(nm, objs, kinds):
    out = set()
    for line in subprocess.run([nm, "-g"] + objs, capture_output=True, text=True, check=True).stdout.split("\n"):
        parts = line.split()
        if len(parts) >= 2 and parts[-2] in kinds and parts[-1].startswith("psx_"):
            out.add(parts[-1])
    return out


def main():
    nm, out = sys.argv[1], sys.argv[2]
    rest = sys.argv[3:]
    split = rest.index("--have")
    want = symbols(nm, rest[1:split], "U")
    have = symbols(nm, rest[split + 1:], "TDBRC")
    missing = sorted(want - have)
    lines = ["/* Generated by tools/gen_stubs.py: SDK functions not implemented yet. */",
             '#include "psx.h"', "",
             "#define STUB(symbol)                         \\",
             "    int symbol(void);                        \\",
             "    int symbol(void)                         \\",
             "    {                                        \\",
             "        static bool reported;                \\",
             "        if (!reported) {                     \\",
             "            reported = true;                 \\",
             "            psx_unimplemented(#symbol + 4);  \\",
             "        }                                    \\",
             "        return 0;                            \\",
             "    }", ""]
    lines += [f"STUB({s})" for s in missing if s != "psx_ram"]
    text = "\n".join(lines) + "\n"
    try:
        if open(out).read() == text:
            return
    except FileNotFoundError:
        pass
    open(out, "w").write(text)
    print(f"stubs: {len(missing)} SDK functions not implemented yet")


if __name__ == "__main__":
    main()
